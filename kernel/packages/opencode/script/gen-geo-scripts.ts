#!/usr/bin/env bun

/* --- GeoCode: serialize the data-reading Python scripts into module constants
 * (docs/GEOKERNEL.md §4.13 构建链).
 *
 * The product ships as a single file with no script assets on disk, and
 * TypeScript cannot import .py — so the scripts become constants here. The
 * generated module is kept in version control (a bare checkout runs with no
 * extra step) and refreshed automatically before every build; the sync test in
 * test/geo/qgis-reader.test.ts makes a stale generation loud. --- */

import path from "node:path"
import { fileURLToPath } from "node:url"
import prettier from "prettier"

const packageRoot = fileURLToPath(new URL("..", import.meta.url))
const scriptsDir = path.join(packageRoot, "src", "geo", "qgis", "scripts")
const out = path.join(packageRoot, "src", "geo", "qgis", "scripts.generated.ts")

export const GEO_SCRIPTS = [
  { file: "vector_read.py", name: "VECTOR_READ_PY" },
  { file: "raster_read.py", name: "RASTER_READ_PY" },
  { file: "raster_preview.py", name: "RASTER_PREVIEW_PY" },
] as const

export async function generateGeoScripts() {
  const constants = await Promise.all(
    GEO_SCRIPTS.map(async (item) => {
      const text = await Bun.file(path.join(scriptsDir, item.file)).text()
      return `export const ${item.name} = ${JSON.stringify(text)}`
    }),
  )

  const raw = [
    "// Auto-generated by script/gen-geo-scripts.ts — do not edit.",
    "// Regenerated before every build; kept in version control so a bare",
    "// checkout runs without an extra step (docs/GEOKERNEL.md §4.13).",
    "",
    ...constants,
    "",
  ].join("\n")

  // Emit prettier-stable output so regeneration is idempotent: a build must
  // never dirty the working tree when the scripts have not changed.
  const config = await prettier.resolveConfig(out)
  await Bun.write(out, await prettier.format(raw, { ...config, filepath: out }))
}

if (import.meta.main) {
  await generateGeoScripts()
  console.log("Generated src/geo/qgis/scripts.generated.ts")
}
